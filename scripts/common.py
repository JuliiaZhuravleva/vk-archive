#!/usr/bin/env python3
"""Общее для всех скриптов: то, что обязано совпадать между ними.

Как зовут хозяина архива. Имя нужно сразу в нескольких местах — им подписаны
собственные реплики внутри чанка, оно уходит в промпт Whisper («голосовое из
переписки такого-то») и в промпт модели, которая опознаёт собеседников.
Держать его копиями по скриптам нельзя: разойдутся незаметно, а чанки и
расшифровки собираются в разное время.

  export VK_OWN_NAME="Ваше имя"

Задавать до первой сборки чанков: имя попадает в текст, то есть в эмбеддинг.
Менять потом — значит пересобирать чанки и пересчитывать векторы.

Прозвища — то, как хозяина зовут в переписке (уменьшительные, ники, латиница).
Нужны identify_deleted.py: обращение к самому себе не должно приниматься за
имя собеседника. Через запятую, сравнение по префиксу, без учёта регистра:

  export VK_OWN_NICKNAMES="имя,уменьшительное,ник"

DSN подключения к Postgres из db/docker-compose.yml. Пароль осознанно
несекретный: база слушает только 127.0.0.1, а сами данные и так лежат
открыто в data/ на том же диске (см. комментарий в docker-compose.yml).
Другой порт/хост — одной переменной:

  export VK_ARCHIVE_DSN="host=127.0.0.1 port=5433 dbname=vk_archive user=vk password=..."

Каталог распакованного экспорта. По умолчанию data/raw — тот, с которого база
собиралась изначально. Заказав у VK новую выгрузку, распакуйте её ОТДЕЛЬНО и
укажите переменной, а не поверх старой:

  export VK_ARCHIVE_RAW="data/raw-20260731"

Так и надо: выгрузки не вложены одна в другую. Из новой пропадает то, что VK
перестал отдавать (удалённые чаты, комментарии к умершим постам, целые разделы),
и старый каталог остаётся единственным носителем этого. Импорт только дополняет
базу, поэтому оба дерева нужны — затирать data/raw новой выгрузкой нельзя.
"""
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

OWN_NAME = os.environ.get("VK_OWN_NAME", "Я")

# Префиксы в нижнем регистре; пустой список — фильтруется только OWN_NAME.
OWN_NICKNAMES = [p.strip().lower()
                 for p in os.environ.get("VK_OWN_NICKNAMES", "").split(",")
                 if p.strip()]

DSN = os.environ.get(
    "VK_ARCHIVE_DSN",
    "host=127.0.0.1 port=5433 dbname=vk_archive user=vk password=vk_local_only")

OLLAMA_EMBED = os.environ.get("VK_OLLAMA_EMBED",
                              "http://127.0.0.1:11434/api/embed")

# Относительный путь считается от корня репозитория, а не от текущего каталога:
# скрипты запускают и из корня, и из scripts/.
ARCHIVE_ROOT = Path(os.environ.get("VK_ARCHIVE_RAW") or (ROOT / "data" / "raw"))
if not ARCHIVE_ROOT.is_absolute():
    ARCHIVE_ROOT = ROOT / ARCHIVE_ROOT
RAW = ARCHIVE_ROOT / "messages"
